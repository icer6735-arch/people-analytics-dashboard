import { readFile } from 'node:fs/promises';
const data = JSON.parse(await readFile(new URL('../data/synthetic-data.json', import.meta.url), 'utf8'));
const sum = (rows, field) => rows.reduce((total, row) => total + (Number(row[field]) || 0), 0);
const actual = (period, department, role) => data.employee_months.filter(row => row.period === period && (!department || row.department_id === department) && (!role || row.role_family === role));
const budgets = (period, department) => data.budgets.filter(row => row.period === period && (!department || row.department_id === department));
const utilization = (actualRows, budgetRows) => {
  const actualCost = sum(actualRows, 'labor_cost');
  if (!budgetRows.length || budgetRows.some(row => row.budget_labor_cost === null)) return 'no-budget';
  const budget = sum(budgetRows, 'budget_labor_cost');
  if (budget === 0) return 'zero-denominator';
  if (actualCost === 0) return 'no-actual';
  return actualCost / budget;
};
const assertions = [];
const check = (name, condition) => assertions.push({ name, passed: Boolean(condition) });
const normal = utilization(actual('2026-09'), budgets('2026-09'));
check('normal utilization is numeric', typeof normal === 'number' && normal > 0);
check('missing department budget returns no-budget', utilization(actual('2026-02', 'BU-C'), budgets('2026-02', 'BU-C')) === 'no-budget');
check('aggregate with one missing budget returns no-budget', utilization(actual('2026-02'), budgets('2026-02')) === 'no-budget');
check('formal zero budget returns zero-denominator', utilization(actual('2026-06', 'BU-B'), budgets('2026-06', 'BU-B')) === 'zero-denominator');
check('no actual remains distinct from zero percent', utilization([], budgets('2026-09', 'BU-A')) === 'no-actual');
const selectedBudget = sum(budgets('2026-09'), 'budget_labor_cost');
const roleFilteredBudget = sum(budgets('2026-09'), 'budget_labor_cost');
check('role filter does not alter department-month budget', selectedBudget === roleFilteredBudget);
const rows = actual('2026-09');
const hc = new Set(rows.map(row => row.synthetic_employee_id)).size;
check('actual HC is derived from distinct employee facts', hc === rows.length);
const result = { passed: assertions.filter(item => item.passed).length, total: assertions.length, assertions };
console.log(JSON.stringify(result, null, 2));
if (result.passed !== result.total) process.exitCode = 1;
